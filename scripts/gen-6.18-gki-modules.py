#!/usr/bin/env python3
"""Generate the static GKI module list for the 6.18 X6871 device tree.

`get_gki_modules_list()` in main-kernel-2026 returns a select(), but MGK's
`mgk_64.bzl` treats the module list as a plain list (append/remove).  Extract
the default (unconditional) GKI lists from the pinned GKI tree and emit them
as a plain .bzl file.  KUnit modules are loaded dynamically from
`//common:bazel/modules.bzl` (`get_kunit_modules_superset("arm64")`).

Usage:
    scripts/gen-6.18-gki-modules.py
    scripts/gen-6.18-gki-modules.py --gki common \
        --out kernel_device_modules-6.18/kernel/kleaf/gki_modules_6.18.bzl
"""

import argparse
import re
import subprocess
import sys


def extract(path, name):
    text = open(path).read()
    m = re.search(r"^%s\s*=\s*\[(.*?)^\]" % re.escape(name), text,
                  re.S | re.M)
    if not m:
        sys.exit(f"ERROR: {name} not found in {path}")
    body = "\n".join(line for line in m.group(1).splitlines()
                      if not line.lstrip().startswith("#"))
    return re.findall(r'"([^"]+)"', body)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--gki", default="common")
    ap.add_argument("--out",
                    default="kernel_device_modules-6.18/kernel/kleaf/"
                            "gki_modules_6.18.bzl")
    args = ap.parse_args()

    src = f"{args.gki}/bazel/modules_private.bzl"
    gki = extract(src, "_COMMON_GKI_MODULES_LIST")
    gki += extract(src, "_ARM64_GKI_MODULES_LIST")

    def dedup(seq):
        seen = set()
        return [x for x in seq if not (x in seen or seen.add(x))]

    gki = dedup(gki)
    try:
        gki_rev = subprocess.check_output(
            ["git", "-C", args.gki, "rev-parse", "--short=12", "HEAD"],
            text=True, stderr=subprocess.DEVNULL,
        ).strip()
    except Exception:
        gki_rev = "unknown"
    lines = [
        "# SPDX-License-Identifier: GPL-2.0",
        "# Generated by scripts/gen-6.18-gki-modules.py from",
        f"# {src} ({gki_rev}).",
        "# Plain lists because MGK needs append/remove; do not edit by hand.",
        "",
        "GKI_MODULES = [",
    ]
    lines += [f'    "{m}",' for m in gki]
    lines += ["]", ""]
    with open(args.out, "w") as f:
        f.write("\n".join(lines))
    print(f"{args.out}: {len(gki)} GKI modules")


if __name__ == "__main__":
    main()
